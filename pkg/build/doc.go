// Package build writes Sigil modules and policies in Go and renders them
// to `.sigil` source in `sigil fmt`'s canonical style.
//
// A platform team that owns a kind in Go can own its vocabulary there too:
// named, reviewed conditions such as `is_frozen`, which every team's
// handwritten rules then read. The rendered file is committed and
// reviewed like any other policy file, and a Go test catches the moment
// it drifts from the code. Why the vocabulary is a module and the facts it
// reads are input: https://sigil.specht-labs.de/understanding/facts-vocabulary-rules/.
//
// # Documents
//
// [Module] and [Policy] build a document against a [policy.Kind]. Their
// body function gets the document and a shadow of the kind's input, a
// zero value whose fields have addresses, and builds statements in the
// style of a test suite: functions nest, and expressions chain.
//
//	freeze := build.Module("deploy.freeze", deploy.Kind, func(m *build.ModuleDoc[deploy.Input], in *deploy.Input) {
//		build.Pub(m, "is_frozen", build.Or(
//			build.Field(&in.Freeze.Unknown),
//			build.In(build.Field(&in.Environment), build.Field(&in.Freeze.Environments)),
//		))
//	})
//
// renders
//
//	// Code generated by pkg/build from freeze.go. DO NOT EDIT.
//
//	module deploy.freeze: DeployApproval@1
//
//	pub let is_frozen = freeze.unknown or environment in freeze.environments
//
// # Expressions
//
// An [Expr] is typed by the Go type a host value of it has, so the Go
// compiler rejects comparing a duration with a string. [Field] reads an
// input by the address of its Go field: the path, `release.soak`, comes
// from the `policy` tags when the document renders. [Lit] writes a Go
// value as a literal, [Raw] splices in Sigil source, and the methods and
// functions of Expr are the operators; the printer adds the parentheses
// the precedence table needs, and only those.
//
// # Output
//
// [FS] renders documents into a file system for [policy.Kind.Load] or
// [policy.Trusted], [Write] writes them to disk, [Diff] fails when the
// files on disk are stale, and [Check] type-checks them against the kind,
// next to the documents written by hand.
//
// # Errors
//
// A builder call never panics. Every mistake, a field the kind doesn't
// have, a let read outside its `when` body, a name declared twice, is
// collected with the Go file and line of the call and returned by
// [Doc.Source] and the output functions as [Errors]. A type error the
// Sigil checker finds names the call of the statement it's in.
//
// The reference of every function and the Sigil it renders is at
// https://sigil.specht-labs.de/reference/go-builder/, and the how-to at
// https://sigil.specht-labs.de/guides/build-policies-in-go/.
