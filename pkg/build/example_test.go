// A vocabulary module: the host resolves a change freeze from its
// feature-flag system into the input, and the module names what the
// facts mean. The live freeze stays data in the input; the module only
// says how to read it.
func ExampleModule() {
	type Freeze struct {
		Environments []string `policy:"environments"` // the frozen environments
		Unknown      bool     `policy:"unknown"`      // the flag system couldn't be asked
	}
	type Input struct {
		Environment string `policy:"environment"`
		Freeze      Freeze `policy:"freeze"`
	}
	deny := policy.NewDecision[policy.None]("deny", "change_freeze", "no_rule_matched")
	kind := policy.NewKind[Input]("DeployApproval",
		policy.WithVersion(1),
		policy.WithDecisions(deny),
		policy.WithDefault(deny.Reason("no_rule_matched")),
	)

	freeze := build.Module("deploy.freeze", kind, func(m *build.ModuleDoc[Input], in *Input) {
		m.Comment("Frozen when the freeze names the environment, or when nobody knows.")
		build.Pub(m, "is_frozen", build.Or(
			build.Field(&in.Freeze.Unknown),
			build.In(build.Field(&in.Environment), build.Field(&in.Freeze.Environments)),
		))
	})

	src, err := freeze.Source()
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Print(string(src))
	// Output:
	// // Code generated by pkg/build from example_test.go. DO NOT EDIT.
	//
	// module deploy.freeze: DeployApproval@1
	//
	// // Frozen when the freeze names the environment, or when nobody knows.
	// pub let is_frozen = freeze.unknown or environment in freeze.environments
}

// A guardrail policy built in Go: a param with bounds, a rule that reads
// the vocabulary of another document, which generates its import, and a
// rule on the input.
func ExamplePolicy() {
	type Release struct {
		Soak   time.Duration `policy:"soak"`
		Hotfix bool          `policy:"hotfix"`
	}
	type Input struct {
		Release Release `policy:"release"`
	}
	deny := policy.NewDecision[policy.None]("deny", "change_freeze", "soak_too_short", "no_rule_matched")
	kind := policy.NewKind[Input]("DeployApproval",
		policy.WithVersion(1),
		policy.WithDecisions(deny),
		policy.WithDefault(deny.Reason("no_rule_matched")),
	)

	freeze := build.Extern("deploy.freeze") // written by hand, or built in Go
	guardrails := build.Policy("deploy.guardrails", kind, func(p *build.PolicyDoc[Input], in *Input) {
		minSoak := build.Param(p, "min_soak", build.Default(24*time.Hour), build.Min(time.Hour), build.Max(48*time.Hour))

		p.When(build.Ref[bool](freeze, "is_frozen"), func(b *build.Block) {
			b.Decide(deny.Reason("change_freeze"))
		})
		p.When(build.And(
			build.Field(&in.Release.Soak).Lt(minSoak),
			build.Not(build.Field(&in.Release.Hotfix)),
		), func(b *build.Block) {
			b.Decide(deny.Reason("soak_too_short"))
		})
	}, build.WithHeader(""))

	src, err := guardrails.Source()
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Print(string(src))
	// Output:
	// policy deploy.guardrails: DeployApproval@1
	//
	// use deploy.freeze.{is_frozen}
	//
	// param min_soak: duration = 24h, min: 1h, max: 48h
	//
	// when is_frozen {
	//   deny(reason: change_freeze)
	// }
	//
	// when release.soak < min_soak and not release.hotfix {
	//   deny(reason: soak_too_short)
	// }
}

// A drift check, as a test runs it: the committed file no longer matches
// what the Go code renders, and the error says how.
func ExampleDiff() {
	type Input struct {
		Environment string `policy:"environment"`
	}
	deny := policy.NewDecision[policy.None]("deny", "no_rule_matched")
	kind := policy.NewKind[Input]("DeployApproval",
		policy.WithVersion(1),
		policy.WithDecisions(deny),
		policy.WithDefault(deny.Reason("no_rule_matched")),
	)
	env := build.Module("deploy.env", kind, func(m *build.ModuleDoc[Input], in *Input) {
		for _, name := range []string{"development", "staging", "canary", "production"} {
			build.Pub(m, name, build.Field(&in.Environment).Eq(build.Lit(name)))
		}
	}, build.WithHeader(""))

	committed := fstest.MapFS{"deploy/env.sigil": {Data: []byte(`module deploy.env: DeployApproval@1

pub let development = environment == "development"
pub let staging = environment == "staging"
pub let canary = environment == "canary"
pub let production = environment == "prod"
`)}}
	fmt.Println(build.Diff(committed, env))
	// Output:
	// build: 1 rendered file(s) out of date; regenerate them from the Go code
	// deploy/env.sigil is stale:
	// --- deploy/env.sigil (on disk)
	// +++ deploy/env.sigil (rendered)
	// @@ -3,4 +3,4 @@
	//  pub let development = environment == "development"
	//  pub let staging = environment == "staging"
	//  pub let canary = environment == "canary"
	// -pub let production = environment == "prod"
	// +pub let production = environment == "production"
}
